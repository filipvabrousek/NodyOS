void font_init(void)
{
    for (int g = 0; g < 95; g++) {
        const char *p = glyphs[g];
        int row = 0, col = 0;
        u8 bits = 0;
        for (;; p++) {
            if (*p == '#' || *p == '.') {
                bits = (u8)((bits << 1) | (*p == '#'));
                if (++col == 5) {
                    if (row < 9) font_rows[g][row] = bits;
                    row++; col = 0; bits = 0;
                }
            }
            if (!*p) break;
        }
    }
}
